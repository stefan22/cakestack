/**
 * Wordmark that strokes each letter on, then fills it in, once per page load.
 */
export function CakeStack({
  className,
  style,
}: {
  className?: string;
  style?: React.CSSProperties;
}) {
  const container = useRef<SVGSVGElement>(null);

  useGSAP(
    () => {
      gsap
        .timeline()
        .set('path', { drawSVG: '0%' })
        .to('path', {
          drawSVG: '100%',
          duration: 0.9,
          stagger: 0.1,
          ease: 'power1.inOut',
        })
        // Staggered to match the draw and started partway into it, so each
        // letter fills as its own stroke lands rather than the whole word
        // waiting for the last one and filling as a separate closing phase.
        .to(
          'path',
          {
            fillOpacity: 1,
            strokeWidth: 2,
            duration: 0.45,
            stagger: 0.1,
            ease: 'power2.out',
          },
          0.75
        );
    },
    { scope: container }
  );

  return (
    <svg
      ref={container}
      viewBox="0 -76 512 80"
      className={className}
      style={style}
      role="img"
      aria-label="CakeStack">
      {LETTERS.map((d) => (
        <path
          key={d}
          d={d}
          fill="currentColor"
          stroke="currentColor"
          // Heavy enough that the draw is visible at nav size (the wordmark
          // renders ~19px tall); the fill step tapers it back to 2.
          strokeWidth="5"
          // Keeps the wordmark hidden in server-rendered markup, until the
          // timeline takes over on hydration.
          fillOpacity="0"
          strokeDasharray="1200"
          strokeDashoffset="1200"
        />
      ))}
    </svg>
  );
}
